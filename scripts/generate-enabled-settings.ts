/**
 * Writes docs/enabled-settings.md: which Lane Pilot settings ship on, by the settings catalog (defaults) and the hub's
 * global `*` rows (snapshot JSON). `npx tsx scripts/generate-enabled-settings.ts [--check] [--db <sqlite path>]`:
 * --db refreshes docs/enabled-settings.snapshot.json from lane_pilot_project_settings where project_id='*';
 * --check exits 1 when the page is stale (tests/enabled-settings.test.ts runs the same check against the fixture).
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SETTING_CATALOG } from "../packages/settings-catalog/src/channels";
import { UI_CATALOG } from "../packages/settings-catalog/src/ui-catalog";
import { DEFAULT_QUALITY_MODE } from "../src/rooms/critique/quality-mode";
import { TASK_ATTEMPT_BUDGET } from "../src/rooms/writer/retry-budget";
import { MAIN_ATTEMPT_LIMIT } from "../src/rooms/runs/state-machine";
import { parseMemorySettings } from "../packages/memory-core/src/settings";

const root = join(import.meta.dirname, "..");
const snapshotPath = join(root, "docs/enabled-settings.snapshot.json");
const target = join(root, "docs/enabled-settings.md");

const dbArg = process.argv.indexOf("--db");
if (dbArg !== -1) {
  const rows = JSON.parse(execFileSync("sqlite3", ["-readonly", "-json", process.argv[dbArg + 1]!,
    "SELECT key,value,updated_at FROM lane_pilot_project_settings WHERE project_id='*' ORDER BY key"], { maxBuffer: 8 << 20 }).toString()) as
    Array<{ key: string; value: string; updated_at: number | null }>;
  writeFileSync(snapshotPath, `${JSON.stringify({ level: "*", fetchedAt: new Date().toISOString(), settings: rows }, null, 2)}\n`);
  console.log(`${snapshotPath}: ${rows.length} global row(s)`);
}

const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8")) as { level: string; fetchedAt: string | null; settings: Array<{ key: string; value: string }> };
const hub = new Map(snapshot.settings.map((row) => [row.key, row.value]));
const defaults = new Map(UI_CATALOG.map((row) => [row.storageKey, row.defaultValue]));

// ponytail: catalog reasons run long; the table keeps the key, the code default and the hub `*` value, plus a flag for the switches.
const SWITCH = /enabled|\.mode$|nightly|default_for_risk/;
const rows = SETTING_CATALOG.filter((spec) => spec.channel === "OWN")
  .map((spec) => {
    const def = defaults.get(spec.key);
    const live = hub.get(spec.key);
    return `| \`${spec.key}\` | ${def === undefined || def === "" ? "—" : `\`${def}\``} | ${live === undefined ? "—" : `\`${live}\``} | ${spec.reason.split(";")[0]!.replace(/^Native Lane Pilot /, "").replace(/\|/g, "\\|")} |`;
  }).sort();

const constants = [
  ["quality_mode (no task/project value)", `\`${DEFAULT_QUALITY_MODE}\``, "resolveQualityMode, src/rooms/critique/quality-mode.ts:10"],
  ["TASK_ATTEMPT_BUDGET", `\`${TASK_ATTEMPT_BUDGET}\``, "src/rooms/writer/retry-budget.ts:8"],
  ["MAIN_ATTEMPT_LIMIT", `\`${MAIN_ATTEMPT_LIMIT}\``, "src/rooms/runs/state-machine.ts:77"],
  ["memory.note_budget", `\`${parseMemorySettings({}).noteBudget}\``, "packages/memory-core/src/settings.ts:53"],
] as const;

const hash = createHash("sha256").update(JSON.stringify([rows, constants, snapshot.settings])).digest("hex").slice(0, 16);

const page = `---
title: Enabled settings (generated)
type: component
created: 2026-10-30
updated: 2026-10-30
status: generated
confidence: high
tags: [settings, generated, stages]
sources:
  - packages/settings-catalog/src/channels.ts
  - packages/settings-catalog/src/ui-catalog.ts
  - src/rooms/critique/quality-mode.ts
  - src/rooms/writer/retry-budget.ts
  - docs/enabled-settings.snapshot.json
---

<!-- enabled-settings:structure ${hash} -->

# Enabled settings (generated)

TL;DR: generated by \`scripts/generate-enabled-settings.ts\` from the settings catalog — not written by hand. Column «\`*\`» is the hub's global row
(\`docs/enabled-settings.snapshot.json\`, refreshed with \`--db <path to the hub data.db>\`; fetched ${snapshot.fetchedAt ?? "never — rerun on the hub"}). A stage setting that is unset is recorded \`skipped\` with reason \`disabled_by_project_setting\`.

## How it works

Every stage and loop reads its switch through \`loadProjectSettings\` (project rows over the \`*\` rows). The defaults below come from the UI catalog's
\`defaultValue\`; where the code holds a different fallback, the constants table states it. \`quality_mode\` of a task or project overrides the critique
switches: \`quick\` disables both critiques, \`full\` enables them (\`src/rooms/critique/quality-mode.ts:16-24\`).

## Settings

| Setting | Catalog default | \`*\` on the hub | What it does |
|---|---|---|---|
${rows.join("\n")}

## Fixed defaults in code

| Setting | Value | Where |
|---|---|---|
${constants.map(([key, value, where]) => `| \`${key}\` | ${value} | ${where} |`).join("\n")}
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  const ok = current.includes(`<!-- enabled-settings:structure ${hash} -->`);
  console.log(ok ? "docs/enabled-settings.md matches the code" : "docs/enabled-settings.md is stale: run npx tsx scripts/generate-enabled-settings.ts");
  process.exit(ok ? 0 : 1);
}
writeFileSync(target, page);
console.log(`docs/enabled-settings.md: ${rows.length} settings, snapshot fetched ${snapshot.fetchedAt ?? "never"}`);
