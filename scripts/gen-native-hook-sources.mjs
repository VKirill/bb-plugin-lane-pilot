// Embeds lane-stack/hooks/*.py into src/rooms/native-install/native-hook-sources.ts, one source line per code line, so no line of the
// file outgrows ripgrep's 64 KB JSON record (writers' searches failed on the old single 61 KB line).
// Run: node scripts/gen-native-hook-sources.mjs
import { readFileSync, writeFileSync } from "node:fs";

const names = ["inject_agent_type.py", "guard_shell.py", "lib_payload.py"];
const body = names.map((name) => {
  const lines = readFileSync(new URL(`../lane-stack/hooks/${name}`, import.meta.url), "utf8").split("\n");
  return `  ${JSON.stringify(name)}: [\n${lines.map((line) => `    ${JSON.stringify(line)},`).join("\n")}\n  ].join("\\n"),`;
}).join("\n");
writeFileSync(new URL("../src/rooms/native-install/native-hook-sources.ts", import.meta.url),
  `// Generated by scripts/gen-native-hook-sources.mjs from lane-stack/hooks; do not edit by hand.\nexport const NATIVE_HOOK_SOURCES: Record<string, string> = {\n${body}\n};\n`);
