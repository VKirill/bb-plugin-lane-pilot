import { createHash } from "node:crypto";

/**
 * The atlas of Lane Pilot (SMA atlas D2-11: «every node and link is taken from the product code»). One pure function turns the code's own
 * registries into a Markdown map: the rooms (one component each, with its public API and size), the task stages and the proof each one gives,
 * the attempt state machine, the memory delivery paths, the RPC methods, and which drill scenario or test covers a room. The structure part
 * carries a hash; a test regenerates it from the registries, so a map that no longer matches the code fails. Sizes are listed apart and are
 * not hashed: they change with every edit. The largest files are the candidates to split into smaller components.
 */
export type AtlasRoom = { name: string; files: number; lines: number; publicExports: string[]; coverage: string };
export type AtlasInput = {
  rooms: AtlasRoom[];
  stages: Array<{ id: string; kind: string; what: string }>;
  transitions: Array<{ from: string | null; event: string; to: string }>;
  memoryPaths: Array<{ id: string; consumer: string; carries: readonly string[] }>;
  rpc: string[];
  /** `bb lane-pilot` subcommands as registered in the CLI room. */
  cli: Array<{ name: string; summary: string }>;
  /** The shipped graphs in workflows/. */
  graphs: Array<{ id: string; name: string; status: string; description: string }>;
  packages: string[];
  /** Sizes for the README numbers: not hashed, they change with every edit. */
  size: { version: string; settings: number; testFiles: number; sourceLines: number };
  largestFiles: Array<{ path: string; lines: number }>;
};

const firstSentence = (text: string) => { const cut = /^(.{20,240}?[.!?])(\s|$)/.exec(text.replace(/\s+/g, " ")); return cut ? cut[1]! : text.slice(0, 240); };
const esc = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

/** The structure the hash covers: names and links only, no sizes. */
export function atlasStructure(input: AtlasInput): string {
  return JSON.stringify({
    rooms: input.rooms.map((room) => [room.name, room.publicExports]).sort(),
    stages: input.stages.map((stage) => [stage.id, stage.kind]),
    transitions: input.transitions.map((row) => [row.from, row.event, row.to]),
    memoryPaths: input.memoryPaths.map((path) => [path.id, [...path.carries]]),
    rpc: [...input.rpc].sort(),
    cli: input.cli.map((command) => command.name).sort(),
    graphs: input.graphs.map((graph) => graph.id).sort(),
    packages: [...input.packages].sort(),
  });
}

export const atlasHash = (input: AtlasInput) => createHash("sha256").update(atlasStructure(input)).digest("hex").slice(0, 16);

export function renderAtlas(input: AtlasInput): string {
  const states = [...new Set(input.transitions.flatMap((row) => [row.from ?? "(new)", row.to]).filter((state) => state !== "stay"))];
  const node = (state: string) => state.replace(/[^A-Za-z0-9_]/g, "_");
  return [
    "---", "title: Atlas of Lane Pilot (generated)", "type: map", "status: generated", "---", "",
    "# Atlas of Lane Pilot", "",
    `> Generated by \`npx tsx scripts/generate-atlas.ts\` from the code's registries. Do not edit by hand. <!-- atlas:structure ${atlasHash(input)} -->`, "",
    `## Rooms (${input.rooms.length})`, "",
    "Each room is one component: `index.ts` is its public API, `server/` its services, `ui/` its screens. Other rooms import only the public API.", "",
    "| room | public API | files | lines | covered by |", "|---|---|---:|---:|---|",
    ...input.rooms.map((room) => `| ${room.name} | ${esc(room.publicExports.join(", ") || "—")} | ${room.files} | ${room.lines} | ${esc(room.coverage || "—")} |`), "",
    `## Task stages (${input.stages.length})`, "",
    "| stage | proof | what decides it |", "|---|---|---|",
    ...input.stages.map((stage) => `| ${stage.id} | ${stage.kind} | ${esc(stage.what)} |`), "",
    `## Attempt state machine (${input.transitions.length} transitions)`, "",
    "```mermaid", "stateDiagram-v2",
    ...input.transitions.map((row) => `  ${node(row.from ?? "(new)")} --> ${node(row.to === "stay" ? (row.from ?? "(new)") : row.to)}: ${row.event}`),
    "```", "", `States: ${states.join(", ")}.`, "",
    `## Memory delivery paths (${input.memoryPaths.length})`, "",
    "| path | consumer | carries |", "|---|---|---|",
    ...input.memoryPaths.map((path) => `| ${path.id} | ${esc(path.consumer)} | ${path.carries.join(", ")} |`), "",
    `## CLI commands (${input.cli.length})`, "",
    "Every `bb lane-pilot <command>`; `bb lane-pilot <command> --help` or the bare `bb lane-pilot` prints the full usage.", "",
    "| command | what it does |", "|---|---|",
    ...[...input.cli].sort((a, b) => a.name.localeCompare(b.name)).map((command) => `| \`${command.name}\` | ${esc(command.summary)} |`), "",
    `## Shipped graphs (${input.graphs.length})`, "",
    "Every piece of work Lane Pilot runs is one of these graphs (`workflows/<id>.json`); `lp.*` are its own maintenance graphs.", "",
    "| graph | name | status | what it does |", "|---|---|---|---|",
    ...input.graphs.map((graph) => `| ${graph.id} | ${esc(graph.name)} | ${graph.status} | ${esc(firstSentence(graph.description))} |`), "",
    `## RPC methods (${input.rpc.length})`, "", [...input.rpc].sort().map((name) => `\`${name}\``).join(" · "), "",
    "## Largest files (candidates to split)", "",
    "| file | lines |", "|---|---:|",
    ...input.largestFiles.map((file) => `| ${file.path} | ${file.lines} |`), "",
  ].join("\n");
}

/** The numbers block of the root README, rewritten with the atlas; it carries the same hash, so a stale README fails the atlas test. */
export function renderReadmeNumbers(input: AtlasInput): string {
  const published = input.graphs.filter((graph) => graph.status === "published").length;
  const own = input.graphs.filter((graph) => graph.id.startsWith("lp.")).length;
  return [
    `<!-- numbers:start ${atlasHash(input)} -->`,
    `| What | Count |`, `|---|---:|`,
    `| Version | ${input.size.version} |`,
    `| Rooms (components in \`src/rooms/\`) | ${input.rooms.length} |`,
    `| Workspace packages (\`packages/\`) | ${input.packages.length} |`,
    `| Shipped graphs (published / own maintenance \`lp.*\`) | ${input.graphs.length} (${published} / ${own}) |`,
    `| Task stages / attempt state transitions | ${input.stages.length} / ${input.transitions.length} |`,
    `| \`bb lane-pilot\` commands | ${input.cli.length} |`,
    `| RPC methods | ${input.rpc.length} |`,
    `| Memory delivery paths | ${input.memoryPaths.length} |`,
    `| Settings in the catalog | ${input.size.settings} |`,
    `| Test files / lines of source (TypeScript, without tests) | ${input.size.testFiles} / ${input.size.sourceLines} |`,
    "",
    "Generated by `npx tsx scripts/generate-atlas.ts` together with [the atlas](docs/atlas.md), which lists every room, command and graph.",
    "<!-- numbers:end -->",
  ].join("\n");
}
