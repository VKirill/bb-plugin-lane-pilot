// Turns src/rooms/council/ui/assets/office-people.glb into office-people-glb.ts (base64), because the plugin
// bundles into one app.js and serves no static assets. Run after replacing the GLB: node scripts/embed-office-people.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "rooms", "council", "ui", "assets");
const base64 = readFileSync(join(dir, "office-people.glb")).toString("base64");
// 4000-character lines: a single 1.8 MB line breaks ripgrep's JSON output (tests/no-huge-lines.test.ts)
const lines = base64.match(/.{1,4000}/g) ?? [];
const source =
  "// Generated by scripts/embed-office-people.mjs from office-people.glb. Do not edit.\n" +
  `export const OFFICE_PEOPLE_GLB_BASE64 = [\n${lines.map((line) => `  "${line}",`).join("\n")}\n].join("");\n`;
writeFileSync(join(dir, "office-people-glb.ts"), source);
console.log(`office-people-glb.ts: ${source.length} bytes`);
