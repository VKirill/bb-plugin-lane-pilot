// Embeds lane-stack/opencode into src/rooms/native-install/native-opencode-sources.ts, one source line per code line.
// Run: node scripts/gen-native-opencode-sources.mjs
import { readFileSync, writeFileSync } from "node:fs";

const names = [
  "opencode-lane.ts",
  "opencode-lane/index.ts",
  "opencode-lane/v2.ts",
  "opencode-lane/guard.ts",
  "opencode-lane/hub-guard.ts",
  "opencode-lane/budget.ts",
  "agents/lane-pilot.md",
];
const body = names.map((name) => {
  const lines = readFileSync(new URL(`../lane-stack/opencode/${name}`, import.meta.url), "utf8").split("\n");
  return `  ${JSON.stringify(name)}: [\n${lines.map((line) => `    ${JSON.stringify(line)},`).join("\n")}\n  ].join("\\n"),`;
}).join("\n");
writeFileSync(new URL("../src/rooms/native-install/native-opencode-sources.ts", import.meta.url),
  `// Generated by scripts/gen-native-opencode-sources.mjs from lane-stack/opencode; do not edit by hand.\nexport const NATIVE_OPENCODE_SOURCES: Record<string, string> = {\n${body}\n};\n`);
