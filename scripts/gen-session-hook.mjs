// Bundles src/rooms/session-hooks/cli.ts into the string the plugin writes at session start.
// The host runs from dist and has no checkout beside it, same as NATIVE_HOOK_SOURCES.
//   node scripts/gen-session-hook.mjs
import { writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const esbuild = join(root, "node_modules/esbuild/bin/esbuild");
const built = spawnSync(esbuild, [
  join(root, "src/rooms/session-hooks/cli.ts"),
  "--bundle", "--platform=node", "--format=esm",
], { encoding: "utf8" });
if (built.status !== 0) {
  process.stderr.write(built.stderr);
  process.exit(built.status ?? 1);
}
const lines = built.stdout.split("\n");
const body = lines.map((line) => `    ${JSON.stringify(line)},`).join("\n");
writeFileSync(join(root, "src/rooms/native-install/session-hook-source.ts"),
  `// Generated by scripts/gen-session-hook.mjs from src/rooms/session-hooks/cli.ts. Do not edit by hand.\nexport const SESSION_HOOK_SOURCE = [\n${body}\n  ].join("\\n");\n`);
