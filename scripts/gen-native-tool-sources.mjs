// Embeds Lane Pilot's bin tools in the single-file host artifact.
// Run: node scripts/gen-native-tool-sources.mjs
import { readFileSync, writeFileSync } from "node:fs";

const lines = readFileSync(new URL("../lane-stack/bin/agent-trash", import.meta.url), "utf8").split("\n");
writeFileSync(new URL("../src/rooms/writer/agent-trash-source.ts", import.meta.url),
  `// Generated by scripts/gen-native-tool-sources.mjs from lane-stack/bin/agent-trash; do not edit by hand.\nexport const AGENT_TRASH_SOURCE = [\n${lines.map((line) => `  ${JSON.stringify(line)},`).join("\n")}\n].join("\\n");\n`);
