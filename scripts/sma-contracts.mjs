#!/usr/bin/env node
// Writes src/rooms/sma-map/contracts.ts: for each SMA card id, the tests that hold Lane Pilot to the card's behaviour. A test names its
// card in its title, `[sma:px_stop] stops the running writer ...`; one test may name several cards. --check exits 1 when the file is stale.
//   node scripts/sma-contracts.mjs [--check]
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const target = join(root, "src", "rooms", "sma-map", "contracts.ts");
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.test\.tsx?$/.test(name)) files.push(path);
  }
};
walk(join(root, "tests"));
for (const pkg of readdirSync(join(root, "packages"))) {
  try { walk(join(root, "packages", pkg, "tests")); } catch { /* a package without tests */ }
}

const TITLE = /\b(?:it|test|describe)(?:\.each\([^)]*\))?\(\s*(["'`])((?:\\.|(?!\1).)*)\1/g;
const byCard = new Map();
for (const file of files.sort()) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(TITLE)) {
    const title = match[2];
    for (const card of title.matchAll(/\[sma:([a-z0-9_]+)\]/g)) {
      const list = byCard.get(card[1]) ?? [];
      list.push(`${relative(root, file)} › ${title.replace(/\s*\[sma:[a-z0-9_]+\]\s*/g, " ").trim()}`);
      byCard.set(card[1], list);
    }
  }
}

const lines = [...byCard.keys()].sort().map((card) => `  ${card}: ${JSON.stringify(byCard.get(card))},`);
const out = `// Generated by scripts/sma-contracts.mjs from the tests that name an SMA card in their title ([sma:<card id>]): the tests that
// hold Lane Pilot to that card's behaviour. Do not edit by hand; tests/sma-map.test.ts checks it is current.
export const SMA_CONTRACT_TESTS: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`;
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) { console.error("src/rooms/sma-map/contracts.ts is stale: run node scripts/sma-contracts.mjs"); process.exit(1); }
  process.exit(0);
}
writeFileSync(target, out);
console.log(`${byCard.size} cards checked by ${[...byCard.values()].reduce((n, list) => n + list.length, 0)} test(s) -> ${relative(root, target)}`);
